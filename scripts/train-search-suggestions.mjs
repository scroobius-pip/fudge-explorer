import { readFile, writeFile } from "node:fs/promises";
import { gzipSync } from "node:zlib";
import { resolve } from "node:path";
import {
  SUGGESTION_FEATURE_NAMES,
  makeSuggestionCandidate,
  makeSuggestionQuery,
  normalizeSuggestionText,
  writeSuggestionFeatures,
} from "../src/lib/fudge/search-suggestion-features.ts";
import { SuggestionCandidateIndex } from "../src/lib/fudge/search-suggestion-index.ts";
import { rankSuggestionCandidateIds } from "../src/lib/fudge/search-suggestion-ranker.ts";

const root = resolve(import.meta.dirname, "..");
const source = resolve(
  root,
  process.argv[2] ?? "../fontofweb/seo/dribbble_search_terms.txt",
);
const output = resolve(root, "src/lib/fudge/search-suggestions.model.ts");
const modelLimit = Number(process.argv[3] ?? 16_384);
const validationModulo = 17;

if (!Number.isSafeInteger(modelLimit) || modelLimit < 1) {
  throw new Error(`Invalid model term limit: ${process.argv[3] ?? ""}`);
}

const sourceTerms = [];
const seen = new Set();
for (const row of (await readFile(source, "utf8")).split(/\r?\n/)) {
  const term = normalizeSuggestionText(row);
  if (
    term.length < 2 ||
    term.length > 64 ||
    term.split(" ").length > 6 ||
    seen.has(term)
  ) {
    continue;
  }
  seen.add(term);
  sourceTerms.push(term);
}
if (sourceTerms.length < modelLimit) {
  throw new Error(`Expected at least ${modelLimit} terms, found ${sourceTerms.length}`);
}

const sourceCount = sourceTerms.length;
const candidates = sourceTerms.map((term, rank) =>
  makeSuggestionCandidate(term, rank, sourceCount),
);
const firstCharacterBuckets = bucketsFor(sourceTerms, (term) => term[0] ?? "");
const firstPairBuckets = bucketsFor(sourceTerms, (term) => term.slice(0, 2));
const weights = new Float64Array(SUGGESTION_FEATURE_NAMES.length);
const positiveFeatures = new Float64Array(weights.length);
const negativeFeatures = new Float64Array(weights.length);
let updates = 0;

for (let epoch = 0; epoch < 2; epoch += 1) {
  for (let step = 0; step < sourceCount; step += 1) {
    const index = epoch === 0 ? step : sourceCount - step - 1;
    if (index < modelLimit && index % validationModulo === 0) continue;
    const term = sourceTerms[index];
    const query = makeSuggestionQuery(trainingQuery(term, index, epoch));
    if (!query) continue;

    const firstPair = firstPairBuckets.get(term.slice(0, 2)) ?? [];
    const firstCharacter = firstCharacterBuckets.get(term[0] ?? "") ?? [];
    const negatives = [
      pickDifferent(firstPair, index, index * 17 + epoch * 31 + 7),
      pickDifferent(firstCharacter, index, index * 29 + epoch * 43 + 11),
      (index * 48_271 + epoch * 65_537 + 97) % sourceCount,
    ];
    for (const negativeIndex of negatives) {
      if (negativeIndex === index) continue;
      updatePair(query, candidates[index], candidates[negativeIndex], 1);
    }

    if (index % 8 === 0 && firstPair.length > 1) {
      const otherIndex = pickDifferent(firstPair, index, index * 13 + 19);
      const preferredIndex = Math.min(index, otherIndex);
      const lowerRankedIndex = Math.max(index, otherIndex);
      const sharedPrefix = makeSuggestionQuery(sourceTerms[preferredIndex].slice(0, 2));
      if (sharedPrefix) {
        updatePair(
          sharedPrefix,
          candidates[preferredIndex],
          candidates[lowerRankedIndex],
          0.35,
        );
      }
    }
  }
}

const modelTerms = sourceTerms.slice(0, modelLimit);
const modelCandidates = candidates.slice(0, modelLimit);
const validation = evaluate(modelTerms, modelCandidates, weights);
if (validation.recallAt5 < 0.55 || validation.mrrAt5 < 0.4) {
  throw new Error(
    `Ranker validation failed: recall@5=${validation.recallAt5.toFixed(3)}, MRR@5=${validation.mrrAt5.toFixed(3)}`,
  );
}

const model = modelTerms.join("\n");
const roundedWeights = [...weights].map((weight) => Number(weight.toFixed(8)));
const metrics = {
  recallAt5: Number(validation.recallAt5.toFixed(4)),
  mrrAt5: Number(validation.mrrAt5.toFixed(4)),
  medianLatencyMs: Number(validation.medianLatencyMs.toFixed(3)),
  p95LatencyMs: Number(validation.p95LatencyMs.toFixed(3)),
};
const contents = `// Generated by scripts/train-search-suggestions.mjs.\nexport const SEARCH_SUGGESTION_SOURCE_COUNT = ${sourceCount};\nexport const SEARCH_SUGGESTION_WEIGHTS = ${JSON.stringify(roundedWeights)} as const;\nexport const SEARCH_SUGGESTION_METRICS = ${JSON.stringify(metrics)} as const;\nexport const SEARCH_SUGGESTION_MODEL = ${JSON.stringify(model)}.split("\\n");\n`;
await writeFile(output, contents);
process.stdout.write(
  [
    `Trained ${weights.length}-feature fuzzy ranker on ${sourceCount} source terms.`,
    `Vocabulary: ${modelTerms.length} phrases; artifact: ${Buffer.byteLength(contents)} bytes raw / ${gzipSync(contents).length} bytes gzip.`,
    `Validation: recall@5 ${metrics.recallAt5}, MRR@5 ${metrics.mrrAt5}; latency ${metrics.medianLatencyMs} ms median / ${metrics.p95LatencyMs} ms p95.`,
    `Weights: ${SUGGESTION_FEATURE_NAMES.map((name, index) => `${name}=${roundedWeights[index]}`).join(", ")}`,
  ].join("\n") + "\n",
);

function updatePair(query, positive, negative, strength) {
  writeSuggestionFeatures(query, positive, positiveFeatures);
  writeSuggestionFeatures(query, negative, negativeFeatures);
  let margin = 0;
  for (let index = 0; index < weights.length; index += 1) {
    margin += weights[index] * (positiveFeatures[index] - negativeFeatures[index]);
  }
  const gain = 1 / (1 + Math.exp(Math.max(-24, Math.min(24, margin))));
  const learningRate = (0.055 * strength) / Math.sqrt(1 + updates / 120_000);
  const regularization = 0.000_002;
  for (let index = 0; index < weights.length; index += 1) {
    const difference = positiveFeatures[index] - negativeFeatures[index];
    weights[index] +=
      learningRate * (gain * difference - regularization * weights[index]);
  }
  updates += 1;
}

function trainingQuery(term, index, epoch) {
  const fractions = [0.46, 0.58, 0.7, 0.82];
  const fraction = fractions[(index + epoch) % fractions.length];
  const length = Math.max(2, Math.min(term.length - 1, Math.ceil(term.length * fraction)));
  let query = term.slice(0, length).trimEnd();
  const variant = (index + epoch * 3) % 5;
  if (variant === 1) query = deleteCharacter(query, index);
  else if (variant === 2) query = transposeCharacters(query, index);
  else if (variant === 3) query = substituteCharacter(query, index);
  else if (variant === 4 && term.includes(" ")) {
    query = term
      .split(" ")
      .slice(0, 3)
      .map((token, tokenIndex) =>
        token.slice(0, Math.max(1, Math.ceil(token.length * (tokenIndex === 0 ? 0.75 : 0.45)))),
      )
      .join(" ");
  }
  return query.trim();
}

function validationQuery(term, index) {
  const length = Math.max(4, Math.min(term.length - 1, Math.ceil(term.length * 0.78)));
  const prefix = term.slice(0, length).trimEnd();
  return index % 2 === 0
    ? transposeCharacters(prefix, index + 3)
    : deleteCharacter(prefix, index + 5);
}

function deleteCharacter(value, seed) {
  if (value.length < 4) return value;
  const positions = letterPositions(value, 1, value.length - 1);
  if (positions.length === 0) return value;
  const index = positions[seed % positions.length];
  return value.slice(0, index) + value.slice(index + 1);
}

function transposeCharacters(value, seed) {
  if (value.length < 4) return value;
  const positions = letterPositions(value, 1, value.length - 1).filter(
    (index) => value[index + 1] && value[index + 1] !== " ",
  );
  if (positions.length === 0) return value;
  const index = positions[seed % positions.length];
  return (
    value.slice(0, index) +
    value[index + 1] +
    value[index] +
    value.slice(index + 2)
  );
}

function substituteCharacter(value, seed) {
  if (value.length < 3) return value;
  const positions = letterPositions(value, 1, value.length);
  if (positions.length === 0) return value;
  const index = positions[seed % positions.length];
  const replacement = String.fromCharCode(97 + ((value.charCodeAt(index) + seed) % 26));
  return value.slice(0, index) + replacement + value.slice(index + 1);
}

function letterPositions(value, start, end) {
  const positions = [];
  for (let index = start; index < end; index += 1) {
    if (value[index] !== " ") positions.push(index);
  }
  return positions;
}

function bucketsFor(terms, keyOf) {
  const buckets = new Map();
  for (let index = 0; index < terms.length; index += 1) {
    const key = keyOf(terms[index]);
    const bucket = buckets.get(key);
    if (bucket) bucket.push(index);
    else buckets.set(key, [index]);
  }
  return buckets;
}

function pickDifferent(bucket, ownIndex, seed) {
  if (bucket.length < 2) return ownIndex;
  let candidate = bucket[Math.abs(seed) % bucket.length];
  if (candidate === ownIndex) {
    candidate = bucket[(Math.abs(seed) + 1) % bucket.length];
  }
  return candidate;
}

function evaluate(modelTerms, modelCandidates, learnedWeights) {
  const validationRows = [];
  for (let index = 0; index < modelTerms.length; index += 1) {
    if (
      index % validationModulo === 0 &&
      modelTerms[index].length >= 6 &&
      validationRows.length < 320
    ) {
      validationRows.push({
        index,
        query: validationQuery(modelTerms[index], index),
      });
    }
  }
  const candidateIndex = new SuggestionCandidateIndex(modelCandidates);

  let hits = 0;
  let reciprocalRank = 0;
  const latencies = [];
  for (const row of validationRows) {
    const startedAt = performance.now();
    const query = makeSuggestionQuery(row.query);
    const top = query
      ? rankSuggestionCandidateIds(
          query,
          modelCandidates,
          candidateIndex,
          learnedWeights,
          5,
        )
      : [];
    latencies.push(performance.now() - startedAt);
    const rankIndex = top.findIndex(
      (candidateId) => candidateId === row.index,
    );
    if (rankIndex >= 0) {
      hits += 1;
      reciprocalRank += 1 / (rankIndex + 1);
    }
  }
  latencies.sort((a, b) => a - b);
  return {
    recallAt5: hits / validationRows.length,
    mrrAt5: reciprocalRank / validationRows.length,
    medianLatencyMs: latencies[Math.floor(latencies.length * 0.5)] ?? 0,
    p95LatencyMs: latencies[Math.floor(latencies.length * 0.95)] ?? 0,
  };
}

